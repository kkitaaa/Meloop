ALTER TABLE USUARIO
    ADD COLUMN IF NOT EXISTS rol VARCHAR(30) NOT NULL DEFAULT 'usuario',
    ADD COLUMN IF NOT EXISTS suspendido BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS es_moderador BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS motivo_suspension TEXT;

ALTER TABLE RECOMPENSA
    ADD COLUMN IF NOT EXISTS nombre VARCHAR(100),
    ADD COLUMN IF NOT EXISTS descripcion TEXT,
    ADD COLUMN IF NOT EXISTS habilitada BOOLEAN NOT NULL DEFAULT TRUE,
    ADD COLUMN IF NOT EXISTS disponible BOOLEAN NOT NULL DEFAULT TRUE;

UPDATE USUARIO
SET rol = 'usuario'
WHERE rol IS NULL;

UPDATE RECOMPENSA
SET habilitada = TRUE, disponible = TRUE
WHERE habilitada IS NULL OR disponible IS NULL;
